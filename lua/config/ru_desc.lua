local verbs = { Toggle = "Переключить", Enable = "Включить", Disable = "Выключить" }

-- хвосты вида "Grep (Root Dir)"
local suffixes = {
  ["Root Dir"] = "корень проекта",
  ["cwd"] = "текущая папка",
}

local cache = {}

local function translate(desc)
  local hit = M.exact[desc]
  if hit then
    return hit
  end
  local verb, thing = desc:match("^(%a+) (.+)$")
  if verbs[verb] and M.things[thing] then
    return verbs[verb] .. " " .. M.things[thing]
  end
  -- mini.pairs: 'Open action for "()" pair'
  local action, pair = desc:match("^(%a+) action for (.+) pair$")
  local actions = { Open = "Открыть пару", Close = "Закрыть пару", Closeopen = "Открыть/закрыть пару" }
  if actions[action] then
    return actions[action] .. " " .. pair
  end
  local base, suffix = desc:match("^(.-) %((.-)%)$")
  if base and M.exact[base] then
    return ("%s (%s)"):format(M.exact[base], suffixes[suffix] or suffix)
  end
end

---@param desc string
---@return string
function M.replace(desc)
  if cache[desc] == nil then
    -- копии маппингов от langmapper: "X LM (translate "...")"
    local clean = desc:gsub(' LM %(translate ".-"%)', ""):gsub("%s+$", "")
    cache[desc] = translate(clean) or clean
  end
  return cache[desc]
end

return M
